/**
 * CDC Title Injector
 *
 * Normalizes article headings before Docsify compiles the main article and
 * wraps Docsify.get for the search plugin. Each article receives one manifest
 * H1, while source H1 headings become H2 sections. This keeps the rendered
 * page and search results at article level without changing Markdown on disk.
 *
 * Must be loaded AFTER docsify.min.js (so the plugin can be registered before
 * DOMContentLoaded) and BEFORE search.min.js (which calls Docsify.get during
 * init).
 *
 * Also clears stale search-index caches to force a fresh rebuild on
 * the first load after deployment.
 */
(function () {
  'use strict';

  /* Generated by scripts/generate-title-map.mjs. */
  var ARTICLE_TITLES = window.CODESOME_ARTICLE_TITLES || {};
  var TITLE_MAP_VERSION = window.CODESOME_ARTICLE_TITLES_VERSION || 'missing';
  var SEARCH_NAMESPACE = 'cdc-titles-v4';
  var pipeline = window.CODESOME_TITLE_PIPELINE = window.CODESOME_TITLE_PIPELINE || {
    version: TITLE_MAP_VERSION,
    status: 'initializing',
    processed: {},
    failures: [],
    dom: {}
  };
  pipeline.version = TITLE_MAP_VERSION;
  pipeline.status = 'initializing';

  function fileNameForUrl(url) {
    try {
      return decodeURIComponent(String(url || '')).split(/[?#]/)[0].split('/').pop();
    } catch (e) {
      return '';
    }
  }

  function failPipeline(reason, fileName) {
    var failure = { reason: String(reason), fileName: fileName || '' };
    pipeline.status = 'failed';
    pipeline.failures.push(failure);
    if (typeof console !== 'undefined' && typeof console.error === 'function') {
      console.error('[Codesome title pipeline] ' + failure.reason + (failure.fileName ? ': ' + failure.fileName : ''));
    }
  }

  function markProcessed(fileName, title) {
    pipeline.status = 'ready';
    pipeline.processed[fileName] = {
      title: title,
      version: TITLE_MAP_VERSION
    };
    pipeline.lastProcessed = fileName;
  }

  /* ── 1. Clear stale search-index caches ─────────────────────────────
 * Old namespaces hold indexes generated before the heading normalization.
 * Remove them so the search plugin builds a fresh index below.
   */
  var STALE_KEYS = [
    'docsify.search.index',
    'docsify.search.expires',
    'docsify.search.index/article-title-v1',
    'docsify.search.expires/article-title-v1',
    'docsify.search.index/cdc-titles-v2',
    'docsify.search.expires/cdc-titles-v2',
    'docsify.search.index/cdc-titles-v3',
    'docsify.search.expires/cdc-titles-v3'
  ];
  STALE_KEYS.forEach(function (k) { try { localStorage.removeItem(k); } catch (e) { /* ignore */ } });

  try {
    var previousTitleMapVersion = localStorage.getItem('codesome.article-titles.version');
    if (previousTitleMapVersion !== TITLE_MAP_VERSION) {
      localStorage.removeItem('docsify.search.index/' + SEARCH_NAMESPACE);
      localStorage.removeItem('docsify.search.expires/' + SEARCH_NAMESPACE);
      localStorage.setItem('codesome.article-titles.version', TITLE_MAP_VERSION);
    }
  } catch (e) { /* ignore */ }

  function demoteHtmlHeadings(line) {
    return line
      .replace(/<h1\b/gi, '<h2')
      .replace(/<\/h1\s*>/gi, '</h2>');
  }

  function normalizeHeadings(content, title, fileName) {
    if (typeof content !== 'string' || content.length === 0) {
      failPipeline('registered article response is empty or not text', fileName);
      return content;
    }

    var source = content.charAt(0) === '\uFEFF' ? content.slice(1) : content;
    var lines = source.split(/\r?\n/);
    var fence = null;
    var normalizedLines = [];

    lines.forEach(function (line, index) {
      var fenceMatch = line.match(/^ {0,3}(`{3,}|~{3,})/);

      if (fenceMatch) {
        if (!fence) {
          fence = fenceMatch[1];
        } else if (
          fenceMatch[1].charAt(0) === fence.charAt(0) &&
          fenceMatch[1].length >= fence.length
        ) {
          fence = null;
        }
        normalizedLines.push(line);
        return;
      }

      if (fence) {
        normalizedLines.push(line);
        return;
      }

      var setextH1 = /^ {0,3}=+\s*$/.test(line);
      if (setextH1 && index > 0) {
        var previousSourceLine = lines[index - 1];
        var previousLine = normalizedLines[normalizedLines.length - 1] || '';
        var previousIsHeading = /^ {0,3}#{1,6}(?:\s|$)/.test(previousSourceLine);
        var previousIsFence = /^ {0,3}(`{3,}|~{3,})/.test(previousSourceLine);
        if (previousLine.trim() && !previousIsHeading && !previousIsFence) {
          normalizedLines[normalizedLines.length - 1] = '## ' + previousLine.trim();
          return;
        }
      }

      normalizedLines.push(
        demoteHtmlHeadings(line).replace(/^( {0,3})#(?=\s+)/, '$1##')
      );
    });

    var normalized = '# ' + title + '\n\n' + normalizedLines.join('\n');
    markProcessed(fileName, title);
    return normalized;
  }

  function currentArticleFileFromHash() {
    var hash = String(window.location && window.location.hash || '');
    var route = hash.replace(/^#\/?/, '').split(/[?#]/)[0];

    if (!route) {
      route = window.$docsify && window.$docsify.homepage || '';
    }

    try {
      route = decodeURIComponent(route);
    } catch (e) { /* fileNameForUrl performs the same safe decode below. */ }

    if (!route || !/\.md$/i.test(route)) {
      route += '.md';
    }

    return fileNameForUrl(route);
  }

  /* ── 2. Normalize the Docsify main-render path ──────────────────────
   * Docsify's renderer fetches through its private Kn/X path, so wrapping
   * Docsify.get alone cannot affect the article displayed on screen. The
   * public beforeEach lifecycle hook receives the exact Markdown that will be
   * compiled, making it the authoritative page-render boundary.
   */
  function titlePipelinePlugin(hook) {
    hook.beforeEach(function (content) {
      var fileName = currentArticleFileFromHash();
      var articleTitle = ARTICLE_TITLES[fileName];

      if (!articleTitle) {
        failPipeline('main-render article has no registered title', fileName);
        return content;
      }

      return normalizeHeadings(content, articleTitle, fileName);
    });
  }

  if (typeof Docsify === 'undefined' || typeof Docsify.get !== 'function') {
    failPipeline('Docsify.get is unavailable; title injector script order is invalid');
    return;
  }

  window.$docsify = window.$docsify || {};
  window.$docsify.plugins = [].concat(
    titlePipelinePlugin,
    window.$docsify.plugins || []
  );
  pipeline.status = 'ready';

  /* ── 3. Wrap Docsify.get ────────────────────────────────────────────
   * Intercept every Docsify fetch for a registered article. Prepend the formal
   * article title for search indexing and demote source H1 headings to H2.
   *
   * The search plugin runs in a later lifecycle and calls Docsify.get, so this
   * wrapper keeps its index consistent with the main-render path above.
   */
  var origGet = Docsify.get;

  Docsify.get = function (url, hasBar, headers) {
    // Decode percent-encoded characters so the URL matches the title map key.
    var fileName = fileNameForUrl(url);
    var articleTitle = ARTICLE_TITLES[fileName];

    // If no registered title exists for this file, pass through unchanged.
    if (!articleTitle) {
      return origGet(url, hasBar, headers);
    }

    // Fetch the raw content and normalize its heading hierarchy.
    var result = origGet(url, hasBar, headers);

    // Handle cached content returned directly as a string.
    if (typeof result === 'string') {
      return normalizeHeadings(result, articleTitle, fileName);
    }

    if (!result || typeof result.then !== 'function') {
      failPipeline('Docsify.get returned a non-thenable article response', fileName);
      return result;
    }

    var origThen = result.then;
    var wrappedResult = {
      then: function (success, error) {
        return origThen.call(result, function (content, opt) {
          if (typeof content === 'string') {
            var normalized = normalizeHeadings(content, articleTitle, fileName);
            return typeof success === 'function' ? success(normalized, opt) : normalized;
          }
          failPipeline('Docsify article response is not text', fileName);
          return typeof success === 'function' ? success(content, opt) : content;
        }, function (reason) {
          failPipeline('Docsify article request failed: ' + (reason && reason.message ? reason.message : reason), fileName);
          return typeof error === 'function' ? error(reason) : undefined;
        });
      }
    };
    if (typeof result.abort === 'function') {
      wrappedResult.abort = function () { return result.abort.apply(result, arguments); };
    }
    return wrappedResult;
  };
})();
