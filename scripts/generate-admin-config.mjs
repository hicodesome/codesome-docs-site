import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { articles } from './cdc-manifest.mjs';
import {
  LATEST_BASELINE_ARTICLES,
  SITE_ONLY_ARTICLES
} from './content-baseline.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'admin/config.yml');
const baselineTitles = new Map(
  LATEST_BASELINE_ARTICLES.map(article => [article.site, article.title])
);
const siteOnlyTitles = new Map(
  SITE_ONLY_ARTICLES.map(article => [article.site, article.title])
);
const seen = new Set();
const allArticles = [];

for (const article of [...articles, ...SITE_ONLY_ARTICLES]) {
  if (seen.has(article.site)) continue;
  seen.add(article.site);
  allArticles.push({
    site: article.site,
    title: baselineTitles.get(article.site) ?? siteOnlyTitles.get(article.site) ?? article.title
  });
}

function yamlString(value) {
  return JSON.stringify(value);
}

const lines = [
  '# Generated by scripts/generate-admin-config.mjs. Edit the manifests instead.',
  'backend:',
  '  name: github',
  '  repo: hicodesome/codesome-docs-site',
  '  branch: main',
  '  api_root: /admin-api/github',
  '  base_url: https://doc.codesome.ai',
  '  auth_endpoint: admin-api/auth',
  '  cms_label_prefix: decap-cms/',
  'publish_mode: editorial_workflow',
  'media_folder: images/uploads',
  'public_folder: /images/uploads',
  'site_url: https://doc.codesome.ai',
  'locale: zh_Hans',
  'collections:',
  '  - name: articles',
  '    label: 公开文章',
  '    files:'
];

for (const [index, article] of allArticles.entries()) {
  lines.push(`      - name: ${yamlString(`article-${index + 1}`)}`);
  lines.push(`        label: ${yamlString(article.title)}`);
  lines.push(`        file: ${yamlString(article.site)}`);
  lines.push('        fields:');
  lines.push('          - label: 正文');
  lines.push('            name: body');
  lines.push('            widget: richtext');
  lines.push('            modes:');
  lines.push('              - rich_text');
  lines.push('              - raw');
  lines.push('            editor_components:');
  lines.push('              - image');
  lines.push('              - code-block');
}

writeFileSync(output, `${lines.join('\n')}\n`, 'utf8');
console.log(`Generated ${allArticles.length} Decap article entries: ${output}`);
