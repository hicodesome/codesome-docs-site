import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { articles } from './cdc-manifest.mjs';
import { SITE_ONLY_ARTICLES } from './content-baseline.mjs';
import { articleTitleEntries } from './title-metadata.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'admin/config.yml');

function yamlString(value) {
  return JSON.stringify(value);
}

export function orderedPublicArticles(
  discoveredArticles,
  preferredArticles = [...articles, ...SITE_ONLY_ARTICLES]
) {
  const seen = new Set();
  const ordered = [];
  const discoveredBySite = new Map(
    discoveredArticles.map(article => [article.site, article])
  );

  for (const article of preferredArticles) {
    const discovered = discoveredBySite.get(article.site);
    if (!discovered || seen.has(article.site)) continue;
    seen.add(article.site);
    ordered.push(discovered);
  }
  for (const article of discoveredArticles) {
    if (seen.has(article.site)) continue;
    seen.add(article.site);
    ordered.push(article);
  }
  return ordered;
}

export function renderAdminConfig(discoveredArticles) {
  const allArticles = orderedPublicArticles(discoveredArticles);
  const lines = [
    '# Generated by scripts/generate-admin-config.mjs from public Markdown. Do not edit manually.',
    'backend:',
    '  name: github',
    '  repo: hicodesome/codesome-docs-site',
    '  branch: main',
    '  api_root: /admin-api/github',
    '  base_url: https://doc.codesome.ai',
    '  auth_endpoint: admin-api/auth',
    '  cms_label_prefix: decap-cms/',
    'publish_mode: editorial_workflow',
    'media_folder: images/uploads',
    'public_folder: /images/uploads',
    'site_url: https://doc.codesome.ai',
    'locale: zh_Hans',
    'collections:',
    '  - name: articles',
    '    label: 公开文章',
    '    files:'
  ];

  for (const [index, article] of allArticles.entries()) {
    lines.push(`      - name: ${yamlString(`article-${index + 1}`)}`);
    lines.push(`        label: ${yamlString(article.title)}`);
    lines.push(`        file: ${yamlString(article.site)}`);
    lines.push('        fields:');
    lines.push('          - label: 正文');
    lines.push('            name: body');
    lines.push('            widget: richtext');
    lines.push('            modes:');
    lines.push('              - rich_text');
    lines.push('              - raw');
    lines.push('            editor_components:');
    lines.push('              - image');
    lines.push('              - code-block');
  }
  return `${lines.join('\n')}\n`;
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const expected = renderAdminConfig(articleTitleEntries);
  if (checkOnly) {
    let current;
    try {
      current = readFileSync(output, 'utf8');
    } catch {
      throw new Error('admin/config.yml is missing; run npm run generate:admin-config');
    }
    if (current !== expected) {
      throw new Error('admin/config.yml is stale; run npm run generate:admin-config');
    }
    console.log(`Decap config check passed: ${articleTitleEntries.length} article entries`);
  } else {
    writeFileSync(output, expected, 'utf8');
    console.log(`Generated ${articleTitleEntries.length} Decap article entries: ${output}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
