#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDocsifyAlias, ROUTE_SLUGS } from './route-slugs.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assetPath = resolve(root, 'assets/route-slugs.js');
const indexPath = resolve(root, 'index.html');
const checkOnly = process.argv.includes('--check');

const slugMap = Object.fromEntries(
  Object.entries(ROUTE_SLUGS).map(([site, slug]) => [slug, site])
);
const version = `slug-map-${createHash('sha256')
  .update(JSON.stringify(slugMap))
  .digest('hex')
  .slice(0, 16)}`;
const alias = buildDocsifyAlias();

const asset =
  '// Generated by scripts/generate-route-slugs.mjs. Do not edit manually.\n' +
  '(function (root) {\n' +
  "  'use strict';\n" +
  '  root.CODESOME_ROUTE_SLUGS = Object.freeze(' +
  JSON.stringify(slugMap, null, 2) +
  ');\n' +
  '  root.CODESOME_ROUTE_SLUGS_VERSION = ' +
  JSON.stringify(version) +
  ';\n' +
  '  root.$docsify = root.$docsify || {};\n' +
  '  root.$docsify.alias = Object.assign({}, root.$docsify.alias || {}, ' +
  JSON.stringify(alias, null, 2) +
  ');\n' +
  '}(window));\n';

function writeOrCheck(target, content, label) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const changed = current !== content;
  if (checkOnly) {
    if (changed) throw new Error(`${label} is stale; run npm run generate:slugs`);
    return false;
  }
  if (changed) writeFileSync(target, content);
  return changed;
}

const assetChanged = writeOrCheck(assetPath, asset, 'assets/route-slugs.js');

const indexText = readFileSync(indexPath, 'utf8');
const scriptPattern = /^  <script src="\.\/assets\/route-slugs\.js\?v=[^"]+"><\/script>\r?\n/gm;
const generatedScript = `  <script src="./assets/route-slugs.js?v=${version}"></script>\n`;
if (!scriptPattern.test(indexText)) {
  throw new Error('index.html must reference ./assets/route-slugs.js?v=...');
}
const docsifyIndex = indexText.indexOf('assets/vendor/docsify.min.js');
const slugIndex = indexText.indexOf('assets/route-slugs.js');
if (slugIndex === -1 || slugIndex > docsifyIndex) {
  throw new Error('assets/route-slugs.js must be loaded before docsify.min.js');
}
const nextIndex = indexText.replace(scriptPattern, generatedScript);
const indexChanged = nextIndex !== indexText;
if (checkOnly && indexChanged) {
  throw new Error('index.html route-slugs version is stale; run npm run generate:slugs');
}
if (!checkOnly && indexChanged) writeFileSync(indexPath, nextIndex);

if (checkOnly) {
  if (assetChanged) throw new Error('assets/route-slugs.js is stale; run npm run generate:slugs');
  console.log(`Route slugs check passed: ${Object.keys(ROUTE_SLUGS).length} slugs, ${Object.keys(alias).length} aliases, version ${version}`);
} else {
  console.log(
    `Route slugs ${assetChanged || indexChanged ? 'generated' : 'unchanged'}: ` +
    `${Object.keys(ROUTE_SLUGS).length} slugs, ${Object.keys(alias).length} aliases, version ${version}`
  );
}
