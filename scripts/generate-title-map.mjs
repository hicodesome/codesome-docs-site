import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { articleTitleEntries } from './title-metadata.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const titleAssetPath = resolve(root, 'assets/article-titles.js');
const indexPath = resolve(root, 'index.html');

function siteArticleSites() {
  return readdirSync(root, { withFileTypes: true })
    .filter(entry => entry.isFile() && /^\d{2}-.*\.md$/.test(entry.name))
    .map(entry => entry.name)
    .sort();
}

const registeredSites = articleTitleEntries.map(article => article.site);
const discoveredSites = siteArticleSites();
if (JSON.stringify(registeredSites) !== JSON.stringify(discoveredSites)) {
  const missing = discoveredSites.filter(site => !registeredSites.includes(site));
  const extra = registeredSites.filter(site => !discoveredSites.includes(site));
  const details = [];
  if (missing.length) details.push(`未登记文章: ${missing.join(', ')}`);
  if (extra.length) details.push(`登记了不存在的文章: ${extra.join(', ')}`);
  throw new Error(`标题元数据与站点文章集合不一致；${details.join('；')}`);
}

const map = Object.fromEntries(articleTitleEntries.map(({ site, title }) => [site, title]));
const canonicalMap = JSON.stringify(map);
const mapHash = createHash('sha256').update(canonicalMap).digest('hex');
const version = `title-map-${mapHash.slice(0, 16)}`;

const asset = `// Generated by scripts/generate-title-map.mjs. Do not edit manually.\n` +
  `(function (root) {\n` +
  `  'use strict';\n` +
  `  root.CODESOME_ARTICLE_TITLES = Object.freeze(${JSON.stringify(map, null, 2)});\n` +
  `  root.CODESOME_ARTICLE_TITLES_VERSION = ${JSON.stringify(version)};\n` +
  `}(window));\n`;

const currentIndex = readFileSync(indexPath, 'utf8');
const titleScriptPattern = /^  <script src="\.\/assets\/article-titles\.js\?v=[^"]+"><\/script>\r?\n/gm;
const withoutGeneratedScript = currentIndex.replace(titleScriptPattern, '');
const injectorScript = '  <script src="./assets/cdc-title-injector.js?v=';
const injectorIndex = withoutGeneratedScript.indexOf(injectorScript);
if (injectorIndex === -1) {
  throw new Error('index.html is missing the cdc-title-injector script');
}
const generatedScript = `  <script src="./assets/article-titles.js?v=${version}"></script>\n`;
const expectedIndex = withoutGeneratedScript.slice(0, injectorIndex) +
  generatedScript +
  withoutGeneratedScript.slice(injectorIndex);

function writeOrCheck(path, expected, label) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
  if (current === expected) return false;
  if (checkOnly) {
    throw new Error(`${label} is stale; run npm run generate:titles`);
  }
  writeFileSync(path, expected, 'utf8');
  return true;
}

const assetChanged = writeOrCheck(titleAssetPath, asset, 'assets/article-titles.js');
const indexChanged = writeOrCheck(indexPath, expectedIndex, 'index.html title-map script reference');

console.log(
  `标题映射${checkOnly ? '检查通过' : '已生成'}：${articleTitleEntries.length} 篇文章，` +
  `版本 ${version}` +
  (checkOnly ? '' : `，文件变化 ${assetChanged || indexChanged ? '有' : '无'}`)
);
